#!/usr/bin/env python3
"""cff_stdenc.py — the CFF Standard Encoding, and what rekha checks itself against.

    python3 scripts/cff_stdenc.py emit   [out.cyr]   # write programs/cff_stdenc_vectors.cyr
    python3 scripts/cff_stdenc.py verify             # cross-check the table against fontTools

WHY THIS EXISTS. A CFF `seac` (the four-argument `endchar`) names its base and accent glyphs by
STANDARD ENCODING CODE, not by glyph id. src/cff.cyr turns a code into an SID with fourteen
contiguous ranges rather than a 256-entry literal, because the table happens to be almost entirely
runs — and a wrong range picks the wrong accent silently, which is the failure mode a font parser
can least afford.

So `emit` writes programs/cff_stdenc_vectors.cyr — all 256 codes and the SID each one means, taken
from the table below and from nothing in rekha — and CI requires the committed file to equal a
fresh emit, exactly as it does for programs/woff2_vectors.cyr and fonts/face_data.cyr.

`verify` re-derives the same table from **fontTools** (`encodings.StandardEncoding` composed with
`cffLib.cffStandardStrings`) and requires a byte-equal match, so the transcription can be re-audited
against an independent implementation. fontTools is NOT a dependency of this repo and CI does not
run that mode.

THE TABLE. `code<TAB>SID`, 256 rows. SID 0 is .notdef, which is also what an unassigned code means.
Verified against fontTools 4.65.0 on 2026-09-20: 149 assigned codes, codes 32..126 running to SIDs
1..95 contiguously.
"""
