def table():
    out = []
    for line in STD_ENCODING.strip().split("\n"):
        c, s = line.split("\t")
        assert int(c) == len(out), line
        out.append(int(s))
    assert len(out) == 256, len(out)
    return out


def emit(path):
    tab = table()
    src = [
        "# programs/cff_stdenc_vectors.cyr — GENERATED by scripts/cff_stdenc.py. DO NOT EDIT.",
        "#",
        "# The CFF Standard Encoding as 256 (code, SID) pairs: what a `seac`'s bchar and achar mean.",
        "# Nothing here is derived from src/cff.cyr — that is the point, since the decoder expresses",
        "# the same table as fourteen arithmetic ranges. CI requires this file to equal a fresh",
        "# `python3 scripts/cff_stdenc.py emit`.",
        "",
        "var REKHA_STDENC_N = 256;",
        "",
        "# Fill `p` with 256 i64 SIDs, indexed by code.",
        "fn cff_stdenc_fill(p): i64 {",
    ]
    # one statement per line: the 120-column lint refuses the packed form, and the formatter
    # is stable on this one (both checked).
    for code, sid in enumerate(tab):
        src.append("    store64(p + %d, %d);" % (code * 8, sid))
    src += ["    return 0;", "}", ""]
    open(path, "w").write("\n".join(src))
    print("wrote %s (256 codes, %d assigned)" % (path, sum(1 for v in tab if v)))


def verify():
    try:
        from fontTools.encodings.StandardEncoding import StandardEncoding
        from fontTools.cffLib import cffStandardStrings
    except ImportError:
        print("fontTools is not installed; `verify` needs it. (CI does not run this mode.)")
        return 2
    sid = {n: i for i, n in enumerate(cffStandardStrings)}
    got = []
    for code in range(256):
        n = StandardEncoding[code] if code < len(StandardEncoding) else None
        got.append(sid.get(n, 0) if n and n != ".notdef" else 0)
    want = table()
    bad = [(c, w, g) for c, (w, g) in enumerate(zip(want, got)) if w != g]
    if bad:
        for c, w, g in bad[:10]:
            print("code %d: embedded SID %d != fontTools %d" % (c, w, g))
        print("MISMATCH in %d of 256 codes" % len(bad))
        return 1
    print("the embedded table matches fontTools exactly: all 256 codes, %d assigned"
          % sum(1 for v in want if v))
    return 0


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "emit":
        emit(sys.argv[2] if len(sys.argv) > 2 else "programs/cff_stdenc_vectors.cyr")
    elif len(sys.argv) == 2 and sys.argv[1] == "verify":
        sys.exit(verify())
    else:
        print(__doc__)
        sys.exit(2)
