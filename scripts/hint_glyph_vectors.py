def row_name(r):
    return "%s %d" % (char_label(r["cp"]), r["ppem"])


def glyph_desc(gf, gid, kind):
    """One line of structure for the header: contours/points, n_ins, and the component records."""
    if kind == "empty":
        return "empty glyph, 0 points"
    if kind.startswith("simple"):
        return "simple, %d-byte program" % gf.simple_n_ins(gid)
    comps, n_ins, _ = gf.components(gid)
    parts = ["[0x%04x gid %d (%d, %d)]" % (fl, g, a1, a2) for fl, g, a1, a2, _ in comps]
    return "composite, %d-byte program, components %s" % (n_ins, " ".join(parts))


