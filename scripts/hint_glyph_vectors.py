# The raw glyf record: what the file says a glyph is, independent of FreeType.
# ----------------------------------------------------------------------------------------------
class Glyf(object):
    """Table directory, loca and glyf of an sfnt, enough to classify a glyph and list its
    component records (the same walk ref2143/ttgload.c:549-736 does)."""

    def __init__(self, data):
        self.data = data
        n = struct.unpack(">H", data[4:6])[0]
        self.tables = {}
        for i in range(n):
            tag, _, off, ln = struct.unpack(">4sIII", data[12 + 16 * i : 28 + 16 * i])
            self.tables[tag] = data[off : off + ln]
        head = self.tables[b"head"]
        self.upem = struct.unpack(">H", head[18:20])[0]
        self.long_loca = struct.unpack(">h", head[50:52])[0] != 0
        self.num_glyphs = struct.unpack(">H", self.tables[b"maxp"][4:6])[0]
        self.loca = self.tables[b"loca"]
        self.glyf = self.tables[b"glyf"]

    def loc(self, g):
        if self.long_loca:
            return struct.unpack(">I", self.loca[4 * g : 4 * g + 4])[0]
        return struct.unpack(">H", self.loca[2 * g : 2 * g + 2])[0] * 2

    def record(self, g):
        a, b = self.loc(g), self.loc(g + 1)
        return self.glyf[a:b] if b > a else b""

    def kind(self, g):
        """'empty', 'simple' or 'composite' from the record's own header."""
        d = self.record(g)
        if len(d) < 10:
            return "empty"
        nc = struct.unpack(">h", d[:2])[0]
        return "composite" if nc < 0 else ("empty" if nc == 0 else "simple")

    def simple_n_ins(self, g):
        d = self.record(g)
        nc = struct.unpack(">h", d[:2])[0]
        p = 10 + 2 * nc
        return struct.unpack(">H", d[p : p + 2])[0]

    def simple_program(self, g):
        d = self.record(g)
        nc = struct.unpack(">h", d[:2])[0]
        p = 10 + 2 * nc
        n = struct.unpack(">H", d[p : p + 2])[0]
        return d[p + 2 : p + 2 + n]

    def components(self, g):
        """[(flags, gid, arg1, arg2, (xx, xy, yx, yy) or None)], n_ins of the composite program
        (0 when the last record lacks WE_HAVE_INSTR), and the program bytes."""
        d = self.record(g)
        p, out = 10, []
        while True:
            flags, gid = struct.unpack(">HH", d[p : p + 4])
            p += 4
            if flags & ARGS_ARE_WORDS:
                fmt = ">hh" if flags & ARGS_ARE_XY_VALUES else ">HH"
                a1, a2 = struct.unpack(fmt, d[p : p + 4])
                p += 4
            else:
                fmt = ">bb" if flags & ARGS_ARE_XY_VALUES else ">BB"
                a1, a2 = struct.unpack(fmt, d[p : p + 2])
                p += 2
            m = None
            if flags & WE_HAVE_A_SCALE:
                s = struct.unpack(">h", d[p : p + 2])[0]
                m = (s, 0, 0, s)
                p += 2
            elif flags & WE_HAVE_AN_XY_SCALE:
                sx, sy = struct.unpack(">hh", d[p : p + 4])
                m = (sx, 0, 0, sy)
                p += 4
            elif flags & WE_HAVE_A_2X2:
                m = struct.unpack(">hhhh", d[p : p + 8])
                p += 8
            out.append((flags, gid, a1, a2, m))
            if not flags & MORE_COMPONENTS:
                break
        n_ins, prog = 0, b""
        if flags & WE_HAVE_INSTR:
            n_ins = struct.unpack(">H", d[p : p + 2])[0]
            prog = d[p + 2 : p + 2 + n_ins]
        return out, n_ins, prog


def flag_names(flags):
    names = []
    for bit, nm in (
        (ARGS_ARE_WORDS, "WORDS"), (ARGS_ARE_XY_VALUES, "XY"), (ROUND_XY_TO_GRID, "ROUND_XY"),
        (WE_HAVE_A_SCALE, "SCALE"), (WE_HAVE_AN_XY_SCALE, "XY_SCALE"), (WE_HAVE_A_2X2, "2X2"),
        (WE_HAVE_INSTR, "INSTR"), (USE_MY_METRICS, "USE_MY_METRICS"),
        (SCALED_COMPONENT_OFFSET, "SCALED_OFFSET"), (UNSCALED_COMPONENT_OFFSET, "UNSCALED_OFFSET"),
    ):
        if flags & bit:
            names.append(nm)
    return " ".join(names)


