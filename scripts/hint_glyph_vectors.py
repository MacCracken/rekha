def resolve(face, tok):
    """A gid from a decimal token, else the cmap index of the character."""
    if tok.isdigit():
        return int(tok), "gid %s" % tok
    return ftshim.char_index(face, tok), repr(tok)


def cmd_rows(argv):
    glyphs, rows, gf = measure_all()
    print("# FreeType %s, %s: %d glyphs, %d rows, %d points" % (
        ftshim.version_string(), FACE, len(glyphs), len(rows), sum(len(r["points"]) for r in rows)))
    for k, (gid, cp, kind, why, ppems) in enumerate(glyphs):
        n = len([r for r in rows if r["glyph"] == k])
        print("%2d %-7s gid %4d %-16s %2d rows  %s" % (k, char_label(cp), gid, kind, n, why))
        print("        " + glyph_desc(gf, gid, kind))


def cmd_dump(argv):
    tok = argv[0] if argv else "H"
    ppem = int(argv[1]) if len(argv) > 1 else 12
    face = open_face()
    gid, label = resolve(face, tok)
    pts, tags, cts, adv = ftshim.load_glyph(face, ppem, gid, 0)
    raw, _, radv = ftshim.hinted(face, ppem, gid, hint=False)
    comp = " composite" if ftshim.is_composite(face, gid) else ""
    print(f"{label} gid={gid}{comp} ppem={ppem} contours={cts} advance {radv} -> {adv} (26.6)")
    print(f"{'i':>4} {'on':>3} {'unhinted':>16} {'hinted':>16}   delta  tag")
    for i, (p, q) in enumerate(zip(raw, pts)):
        on = tags[i] & 1
        d = (q[0] - p[0], q[1] - p[1])
        mark = "   " if d == (0, 0) else " * "
        print(f"{i:>4} {on:>3} {str(p):>16} {str(q):>16}{mark}{str(d) if d != (0, 0) else '':<10} {tags[i]}")
    print(f"digest 0x{digest(pts):016x}")


def cmd_table(argv):
    face = open_face()
    print(f"# FreeType {ftshim.version_string()} interpreter-version {ftshim.INTERPRETER_VERSION}, {FACE}, "
          f"fpgm warmed at {WARM_PPEM} ppem")
    print(f"# {'ch':>3} {'gid':>5} {'ppem':>5} {'pts':>5} {'adv':>6}  digest")
    for ch in CHARS:
        gid = ftshim.char_index(face, ch)
        comp = "composite" if ftshim.is_composite(face, gid) else ""
        for ppem in PPEMS:
            pts, tags, adv = ftshim.hinted(face, ppem, gid)
            print(f"  {ch!r:>3} {gid:>5} {ppem:>5} {len(pts):>5} {adv:>6}  0x{digest(pts):016x} {comp}")


def cmd_sweep(argv):
    """How much of the face the oracle covers, split the way rekha will have to."""
    import collections

    face = open_face()
    n = face.num_glyphs
    kinds = collections.Counter()
    moved = 0
    for gid in range(n):
        try:
            pts, _, _ = ftshim.hinted(face, SWEEP_PPEM, gid)
            raw, _, _ = ftshim.hinted(face, SWEEP_PPEM, gid, hint=False)
        except ftshim.FTError:
            kinds["error"] += 1
            continue
        kinds["composite" if ftshim.is_composite(face, gid) else "simple"] += 1
        if pts != raw:
            moved += 1
    print(f"{FACE}: {dict(kinds)}, {moved} of {n} glyphs move under hinting at {SWEEP_PPEM} ppem")


def main():
    cmds = {"emit": None, "dump": cmd_dump, "table": cmd_table, "sweep": cmd_sweep, "rows": cmd_rows}
    if len(sys.argv) < 2 or sys.argv[1] not in cmds:
        print(__doc__)
        return 2
    if sys.argv[1] == "emit":
        emit(sys.argv[2] if len(sys.argv) > 2 else "programs/hint_glyph_vectors.cyr")
        return 0
    return cmds[sys.argv[1]](sys.argv[2:]) or 0


if __name__ == "__main__":
    sys.exit(main())
