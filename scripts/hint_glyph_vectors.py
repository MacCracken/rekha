#!/usr/bin/env python3
"""FreeType's own hinted outlines of the embedded face, as the oracle for rekha's glyph zone (0.8.2).

⛔ THIS SCRIPT IS THE ONE PIECE OF EVIDENCE rekha CANNOT PRODUCE FOR ITSELF on a real font.
programs/hint_unit_vectors.cyr (scripts/hint_unit_vectors.py) pins every point instruction on a
synthetic glyph; this one runs Liberation Sans's actual glyph programs — fpgm, prep and all —
through the interpreter the world's hinted fonts were drawn against, and records the result
point for point. Its consumer is programs/hint_test.cyr's group P (0.8.2, the release that loads
a glyph into zone 1 and answers a hinted outline), which reads the emitted module
programs/hint_glyph_vectors.cyr the way group K reads hint_unit_vectors.cyr.

FreeType is reached through scripts/ftshim.py: the CLASSIC interpreter (`GETINFO` 35), which is
what src/hint.cyr implements — the default since FreeType 2.7 is version 40, whose minimal
subpixel hinting suppresses every horizontal move (at 12 ppem it leaves the 'H' stem at x=420
where v35 puts it at 439) — and FT_LOAD_NO_AUTOHINT. The reference is FreeType 2.14.3; ftshim
refuses any other 2.x minor, because CI's Ubuntu ships 2.13.2 and its move arithmetic differs.

Every face is WARMED once at a throwaway ppem before anything is measured: FreeType runs `fpgm`
at the first size a face is hinted at, with that size's metrics (2.14.3, C2 B5), so a table whose
first row ran fpgm at 8 ppem would differ from one that started at 48 wherever fpgm asked MPPEM.
rekha does the same (D11: fpgm once, at the first size asked for); the consumer builds its first
context at WARM_PPEM before it compares anything.

THE ROWS. The 18 characters of CHARS (all simple glyphs with a program) at the 10 ppems of PPEMS,
plus the SPECIAL glyphs — composites (accented letters with USE_MY_METRICS on component 0 and a
composite program, one program-less composite, the one composite whose program contains IUP, a
composite of an empty glyph, two whose scaled offsets land on an exact negative half pixel where
FreeType's floor rounding and half-away rounding disagree), the space (an empty glyph: four
phantoms, no outline) and a program-less simple glyph. Every special is picked BY GID with its
reason stated in SPECIALS; the emitter cross-checks the gid against the cmap where the glyph has
a code point, and against the raw glyf record for the structural claims (composite or not,
program or not, USE_MY_METRICS), so a different face fails loudly instead of emitting a table
that pins the wrong glyph. Size budget: simple rows (and the empty glyph) at all 10 ppems,
composite rows at COMPOSITE_PPEMS only — 12, 16 and 24, which are where é's, Ä's, ½'s and ľ's
composite programs are seen to act and where ͼ (12) and ͣ (24) hit their negative halves — so
the module stays near 4,500 lines instead of 5,600; the header of the module says so.

EVERY ROW IS ALSO LOADED UNDER FT_LOAD_PEDANTIC on a second face (warmed pedantic too) and must
give the same points, tags and advance: the proof that FreeType skipped nothing silently on any
row (a bad point index, a short stack, a cvt index out of range fail the load in pedantic mode
and pass with the instruction dropped otherwise).

WHAT A ROW RECORDS is exactly what FreeType's glyph slot holds after FT_Load_Glyph, nothing
derived: every outline point's x and y in F26Dot6 AS REPORTED — after TT_Load_Glyph translated
the outline by -pp1.x (ref2143/ttgload.c:2578-2583; on this face lsb == xMin for every glyph, so
pp1.x is 0 and the translation subtracts 0), the raw tag byte (on-curve 1, touch-x 8, touch-y 16,
and on the first point of every glyph or component whose program ran, 4 | scan_type << 5), the
contour ends, and slot->advance.x (the base layer's FT_PIX_ROUND_LONG of pp2.x - pp1.x). The
unhinted scaled outline is NOT recorded: rekha computes it.

THE EMITTER CHECKS ITS OWN OUTPUT before writing it (the gates of scripts/hint_unit_vectors.py,
imported from there): no line over 120 bytes, none of cyrlint's deferral words, `cyrius lint
--strict` with zero warn/deferral lines, `cyrius fmt` on a copy that must come back
byte-identical. Any failure leaves the destination untouched. The output is deterministic: two
emits on the same host and FreeType are byte-identical.

No freetype-py, no fontTools. NOT RUN IN CI: CI's Ubuntu ships FreeType 2.13.2, whose move
arithmetic, ODD/EVEN, stack margin and DELTAP pops differ from the 2.14.3 rekha targets; the
committed module is regenerated by hand on a 2.14.x host and reviewed like any other
transcription. Python 3 stdlib only. Modes:

    python3 scripts/hint_glyph_vectors.py emit programs/hint_glyph_vectors.cyr
    python3 scripts/hint_glyph_vectors.py table            # the 18 x 10 digest table (0.8.1's)
    python3 scripts/hint_glyph_vectors.py dump H 12        # every point of one glyph (char or gid)
    python3 scripts/hint_glyph_vectors.py sweep            # how much of the face hinting moves
    python3 scripts/hint_glyph_vectors.py rows             # the row list with reasons and counts
"""
