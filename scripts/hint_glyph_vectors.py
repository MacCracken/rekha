def char_label(cp):
    """'H' for a printable ASCII code point, else U+XXXX — the row name and the header's label."""
    if cp is not None and 0x21 <= cp <= 0x7E:
        return chr(cp)
    return "U+%04X" % cp if cp is not None else "gid"


def glyph_list(face, gf):
    """[(gid, cp, kind, why, ppems)] — the 18 characters then the specials, each cross-checked
    against the cmap and the raw glyf record."""
    out = []
    for ch in CHARS:
        gid = ftshim.char_index(face, ch)
        assert gf.kind(gid) == "simple" and gf.simple_n_ins(gid) > 0, (ch, gid)
        out.append((gid, ord(ch), "simple", "a simple glyph with a program (0.8.1's oracle)", PPEMS))
    for gid, cp, kind, umm, why in SPECIALS:
        assert gid < gf.num_glyphs, gid
        if cp is not None:
            assert ftshim.char_index(face, cp) == gid, "gid %d is not U+%04X on this face" % (gid, cp)
        raw = gf.kind(gid)
        if kind == "empty":
            assert raw == "empty", (gid, raw)
            ppems = PPEMS
        elif kind == "simple-noprog":
            assert raw == "simple" and gf.simple_n_ins(gid) == 0, (gid, raw)
            ppems = PPEMS
        else:
            assert raw == "composite", (gid, raw)
            comps, n_ins, _ = gf.components(gid)
            assert (n_ins > 0) == (kind == "composite"), (gid, kind, n_ins)
            assert bool(comps[0][0] & USE_MY_METRICS) == umm, (gid, hex(comps[0][0]))
            ppems = COMPOSITE_PPEMS
        out.append((gid, cp, kind, why, ppems))
    return out


def measure_row(face, strict, gid, ppem):
    """One row: FreeType's reported points, tags, contour ends and advance, and the same load
    under FT_LOAD_PEDANTIC on the second face, which must agree."""
    points, tags, ends, adv = ftshim.load_glyph(face, ppem, gid, 0)
    p2, t2, e2, a2 = ftshim.load_glyph(strict, ppem, gid, ftshim.FT_LOAD_PEDANTIC)
    assert (p2, t2, e2, a2) == (points, tags, ends, adv), "gid %d at %d: pedantic differs" % (gid, ppem)
    return {"gid": gid, "ppem": ppem, "points": points, "tags": tags, "ends": ends, "advance": adv}


def measure_all():
    face, strict = open_face(), open_face(pedantic=True)
    gf = Glyf(open(FACE, "rb").read())
    glyphs = glyph_list(face, gf)
    rows = []
    for k, (gid, cp, kind, why, ppems) in enumerate(glyphs):
        first = None
        for ppem in ppems:
            r = measure_row(face, strict, gid, ppem)
            r["glyph"], r["cp"], r["kind"] = k, cp, kind
            if first is None:
                first = r
            # the structure is the glyph's, not the size's: one table of ends per glyph
            assert (len(r["points"]), r["ends"]) == (len(first["points"]), first["ends"]), (gid, ppem)
            rows.append(r)
    ftshim.done(face)
    ftshim.done(strict)
    return glyphs, rows, gf


