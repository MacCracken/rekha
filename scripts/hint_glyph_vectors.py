def fnv_u32(h, v):
    """The 32-bit-wide feed programs/face_test.cyr uses, in 64-bit FNV-1a."""
    v &= M64
    for i in range(4):
        h = ((h ^ ((v >> (i * 8)) & 255)) * FNV_PRIME) & M64
    return h


def digest(points):
    h = FNV_OFFSET
    for x, y in points:
        h = fnv_u32(h, x)
        h = fnv_u32(h, y)
    return h


def open_face(pedantic=False):
    """The embedded face, warmed: its fpgm has run at WARM_PPEM before any row is measured (the
    pedantic twin is warmed pedantic, so fpgm and prep are checked too)."""
    face = ftshim.load_face(FACE)
    ftshim.hinted(face, WARM_PPEM, ftshim.char_index(face, "H"), pedantic=pedantic)
    return face


